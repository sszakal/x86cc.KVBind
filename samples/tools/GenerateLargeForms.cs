// Generates the large-form models of the sample (Phase 2 of the performance demo): one model per size, each
// a root of 25-field sections cycling through ten field kinds with their value rules, allowed values and
// defaults, plus a line-item collection with a derived total, a nested party and a SUBMIT operation, so
// a thousand-field form still exercises every runtime path.
//
// Run from the repository root after changing it:
//   dotnet run samples/tools/GenerateLargeForms.cs
// The output (samples/x86cc.KVBind.Sample.Api/LargeForms/LargeForm{N}.Generated.cs) is committed.

#pragma warning disable MA0011, S6966 // a one-off code generator: invariant ASCII output, sync I/O

using System.Text;

int[] sizes = [100, 500, 1000, 2000];
const int FieldsPerSection = 25;
var outputDirectory = Path.Combine("samples", "x86cc.KVBind.Sample.Api", "LargeForms");
Directory.CreateDirectory(outputDirectory);

foreach (var size in sizes)
{
    var path = Path.Combine(outputDirectory, $"LargeForm{size}.Generated.cs");
    File.WriteAllText(path, Generate(size));
    Console.WriteLine($"{path}: {size} section fields");
}

static string Generate(int size)
{
    var root = $"LargeForm{size}";
    var sections = size / FieldsPerSection;
    var code = new StringBuilder();
    code.AppendLine("// <auto-generated>");
    code.AppendLine("// Generated by samples/tools/GenerateLargeForms.cs — do not edit; change the generator and rerun it.");
    code.AppendLine("// </auto-generated>");
    code.AppendLine("#pragma warning disable");
    code.AppendLine("using x86cc.KVBind.Core;");
    code.AppendLine("using x86cc.KVBind.Core.Definitions;");
    code.AppendLine();
    code.AppendLine("namespace x86cc.KVBind.Sample.Api.LargeForms;");
    code.AppendLine();

    // ── Model classes ──
    code.AppendLine($"public partial class {root} : KVRootNode");
    code.AppendLine("{");
    code.AppendLine("    [KVBind(\"Status\")] public partial string? Status { get; set; }");
    code.AppendLine("    [KVBind(\"LinesTotal\")] public partial decimal LinesTotal { get; set; }");
    code.AppendLine("    [KVBind(\"LineCount\")] public partial int LineCount { get; set; }");
    for (var s = 1; s <= sections; s++)
    {
        code.AppendLine($"    [KVBind(\"S{s:000}\")] public {root}Section{s:000} S{s:000} {{ get; }} = new();");
    }

    code.AppendLine($"    [KVBind(\"Lines\")] public KVCollectionNode<{root}Line> Lines {{ get; }} = new();");
    code.AppendLine($"    [KVBind(\"Party\")] public partial {root}Party? Party {{ get; private set; }}");
    code.AppendLine();
    code.AppendLine("    public bool IsSubmitted => this.Status == \"submitted\";");
    code.AppendLine();
    code.AppendLine("    protected override KVValidationProfile GetValidationProfile() =>");
    code.AppendLine("        this.IsSubmitted ? new LargeFormSubmitProfile() : KVDefaultValidationProfile.Instance;");
    code.AppendLine();
    code.AppendLine("    public void Submit()");
    code.AppendLine("    {");
    code.AppendLine("        this.Status = \"submitted\";");
    code.AppendLine("        this.Raise(new LargeFormSubmitted(this.LineCount, this.LinesTotal));");
    code.AppendLine("    }");
    code.AppendLine();
    code.AppendLine($"    public void RecalculateLines(KVChangeContext<{root}> context)");
    code.AppendLine("    {");
    code.AppendLine("        var total = 0m;");
    code.AppendLine("        var count = 0;");
    code.AppendLine("        foreach (var line in this.Lines)");
    code.AppendLine("        {");
    code.AppendLine("            total += line.Amount ?? 0m;");
    code.AppendLine("            count++;");
    code.AppendLine("        }");
    code.AppendLine();
    code.AppendLine("        this.LinesTotal = total;");
    code.AppendLine("        this.LineCount = count;");
    code.AppendLine("    }");
    code.AppendLine("}");
    code.AppendLine();

    for (var s = 1; s <= sections; s++)
    {
        code.AppendLine($"public partial class {root}Section{s:000} : KVFieldGroupNode");
        code.AppendLine("{");
        for (var f = 1; f <= FieldsPerSection; f++)
        {
            var field = FieldOf(s, f);
            code.AppendLine($"    [KVBind(\"{field.Name}\")] public partial {field.ClrType} {field.Name} {{ get; set; }}");
        }

        code.AppendLine("}");
        code.AppendLine();
    }

    code.AppendLine($"public partial class {root}Line : KVCollectionItemNode");
    code.AppendLine("{");
    foreach (var (name, type) in LineFieldList())
    {
        code.AppendLine($"    [KVBind(\"{name}\")] public partial {type} {name} {{ get; set; }}");
    }

    code.AppendLine("}");
    code.AppendLine();
    code.AppendLine($"public abstract partial class {root}Party : KVNestedNode;");
    code.AppendLine();
    code.AppendLine($"public partial class {root}Person : {root}Party");
    code.AppendLine("{");
    code.AppendLine("    [KVBind(\"FullName\")] public partial string? FullName { get; set; }");
    code.AppendLine("    [KVBind(\"BirthDate\")] public partial DateOnly? BirthDate { get; set; }");
    code.AppendLine("}");
    code.AppendLine();
    code.AppendLine($"public partial class {root}Organization : {root}Party");
    code.AppendLine("{");
    code.AppendLine("    [KVBind(\"LegalName\")] public partial string? LegalName { get; set; }");
    code.AppendLine("    [KVBind(\"TaxId\")] public partial string? TaxId { get; set; }");
    code.AppendLine("}");
    code.AppendLine();

    // ── Definition ──
    code.AppendLine($"public sealed class {root}DefinitionBuilder : IKVModelDefinitionBuilder");
    code.AppendLine("{");
    code.AppendLine($"    public const int SectionCount = {sections};");
    code.AppendLine($"    public const int SectionFieldCount = {size};");
    code.AppendLine();
    code.AppendLine($"    public Type ModelType => typeof({root});");
    code.AppendLine();
    code.AppendLine("    public KVNodeDefinition Build()");
    code.AppendLine("    {");
    code.AppendLine($"        var builder = new KVBindBuilder<{root}>();");
    code.AppendLine("        builder.Field(x => x.Status, f => f.Default(\"draft\").PatchReadOnly().AllowedValue(\"draft\", \"draft\", \"Draft\").AllowedValue(\"submitted\", \"submitted\", \"Submitted\"));");
    code.AppendLine("        builder.Field(x => x.LinesTotal, f => f.DisplayName(\"Lines Total\").PatchReadOnly());");
    code.AppendLine("        builder.Field(x => x.LineCount, f => f.DisplayName(\"Line Count\").PatchReadOnly());");
    for (var s = 1; s <= sections; s++)
    {
        var resettable = s % 4 == 0 ? ".Resettable()" : string.Empty;
        code.AppendLine($"        builder.FieldGroup(x => x.S{s:000}, g =>");
        code.AppendLine("        {");
        for (var f = 1; f <= FieldsPerSection; f++)
        {
            var field = FieldOf(s, f);
            code.AppendLine($"            g.Field(x => x.{field.Name}, f => f.DisplayName(\"{field.Label}\"){field.Options});");
        }

        code.AppendLine($"        }}, o => o.DisplayName(\"Section {s}\"){resettable});");
    }

    code.AppendLine("        builder.Collection(x => x.Lines, lines =>");
    code.AppendLine("        {");
    code.AppendLine("            lines.DisplayName(\"Lines\");");
    code.AppendLine($"            lines.Item<{root}Line>(\"LINE\", line =>");
    code.AppendLine("            {");
    code.AppendLine("                line.Field(x => x.Description, f => f.DisplayName(\"Description\").MaxLength(200).Annotate(\"ui:title\", true));");
    code.AppendLine("                line.Field(x => x.Quantity, f => f.DisplayName(\"Quantity\").Range(0, 100000).Default(1));");
    code.AppendLine("                line.Field(x => x.UnitPrice, f => f.DisplayName(\"Unit Price\").Min(0m));");
    code.AppendLine("                line.Field(x => x.Amount, f => f.DisplayName(\"Amount\").Min(0m));");
    code.AppendLine("                line.Field(x => x.Category, f => f.DisplayName(\"Category\").AllowedValue(\"goods\", \"goods\", \"Goods\").AllowedValue(\"services\", \"services\", \"Services\").AllowedValue(\"fees\", \"fees\", \"Fees\"));");
    code.AppendLine("                line.Field(x => x.Taxable, f => f.DisplayName(\"Taxable\").Default(true));");
    code.AppendLine("                line.Field(x => x.ServiceDate, f => f.DisplayName(\"Service Date\"));");
    code.AppendLine("                line.Field(x => x.Reference, f => f.DisplayName(\"Reference\").Pattern(\"[A-Z]{3}-[0-9]{3}\"));");
    code.AppendLine("                line.Field(x => x.DiscountPercent, f => f.DisplayName(\"Discount %\").Range(0m, 100m));");
    code.AppendLine("                line.Field(x => x.Notes, f => f.DisplayName(\"Notes\").MaxLength(500).Annotate(\"ui:control\", \"textarea\"));");
    code.AppendLine("            });");
    code.AppendLine("            lines.MaxCount(1000);");
    code.AppendLine("            lines.AggregateSum(\"Amount\").LessThanOrEqual(1_000_000_000m);");
    code.AppendLine("        });");
    code.AppendLine("        builder.NestedNode(x => x.Party, party => party");
    code.AppendLine("            .DisplayName(\"Party\")");
    code.AppendLine($"            .Bind<{root}Person>(\"PERSON\", p => {{ p.Field(x => x.FullName, f => f.DisplayName(\"Full Name\")); p.Field(x => x.BirthDate, f => f.DisplayName(\"Birth Date\")); }})");
    code.AppendLine($"            .Bind<{root}Organization>(\"ORGANIZATION\", o => {{ o.Field(x => x.LegalName, f => f.DisplayName(\"Legal Name\")); o.Field(x => x.TaxId, f => f.DisplayName(\"Tax Id\").Pattern(\"[A-Z]{{2}}[0-9]{{8}}\")); }})");
    code.AppendLine($"            .DefaultType<{root}Organization>());");
    code.AppendLine("        builder.Operation(\"SUBMIT\", x => x.Submit);");
    code.AppendLine("        builder.OnChange(path => path.Collection(x => x.Lines).Field(x => x.Amount), x => x.RecalculateLines);");
    code.AppendLine("        builder.OnChange(path => path.Collection(x => x.Lines).Any(), x => x.RecalculateLines);");
    code.AppendLine("        return builder.Build();");
    code.AppendLine("    }");
    code.AppendLine("}");
    return code.ToString();
}

// The ten field kinds a section cycles through, each with the rules and options the DSL can declare.
static (string Name, string ClrType, string Label, string Options) FieldOf(int section, int index)
{
    var kind = (section + index) % 10;
    var name = $"F{index:00}";
    var requiredOnSubmit = (section * 31 + index) % 7 == 0
        ? ".Validation(p => p.For<LargeFormSubmitProfile>(r => r.Required()))"
        : string.Empty;
    return kind switch
    {
        0 => (name + "Text", "string?", $"Text {section}.{index}", ".MaxLength(80)" + requiredOnSubmit),
        1 => (name + "Count", "int?", $"Count {section}.{index}", ".Range(0, 10000)" + requiredOnSubmit),
        2 => (name + "Amount", "decimal?", $"Amount {section}.{index}", ".Min(0m)" + requiredOnSubmit),
        3 => (name + "Flag", "bool", $"Flag {section}.{index}", ".Default(false)"),
        4 => (name + "Date", "DateOnly?", $"Date {section}.{index}", ".Max(new DateOnly(2099, 12, 31))" + requiredOnSubmit),
        5 => (name + "Choice", "string?", $"Choice {section}.{index}",
            ".AllowedValue(\"a\", \"a\", \"Alpha\").AllowedValue(\"b\", \"b\", \"Bravo\").AllowedValue(\"c\", \"c\", \"Charlie\").AllowedValue(\"d\", \"d\", \"Delta\").AllowedValue(\"e\", \"e\", \"Echo\")" + requiredOnSubmit),
        6 => (name + "Tags", "string[]?", $"Tags {section}.{index}",
            ".AllowedElementValue<string>(\"red\", \"red\", \"Red\").AllowedElementValue<string>(\"green\", \"green\", \"Green\").AllowedElementValue<string>(\"blue\", \"blue\", \"Blue\").AllowedElementValue<string>(\"amber\", \"amber\", \"Amber\")"),
        7 => (name + "Code", "string?", $"Code {section}.{index}", ".Pattern(\"[A-Z]{3}-[0-9]{3}\")" + requiredOnSubmit),
        8 => (name + "Percent", "decimal?", $"Percent {section}.{index}", ".Range(0m, 100m)"),
        _ => (name + "Note", "string?", $"Note {section}.{index}", ".MaxLength(500).Annotate(\"ui:control\", \"textarea\")"),
    };
}

static (string Name, string Type)[] LineFieldList() =>
[
    ("Description", "string?"),
    ("Quantity", "int"),
    ("UnitPrice", "decimal?"),
    ("Amount", "decimal?"),
    ("Category", "string?"),
    ("Taxable", "bool"),
    ("ServiceDate", "DateOnly?"),
    ("Reference", "string?"),
    ("DiscountPercent", "decimal?"),
    ("Notes", "string?"),
];
